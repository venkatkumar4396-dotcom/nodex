/**
 * Resolves nodeType to a clean, crisp SVG icon without any emojis.
 */
export function renderNodeIcon(nodeType = '', label = '', size = 15) {
  const type = String(nodeType || '').toLowerCase();
  const lbl = String(label || '').toLowerCase();

  if (type.includes('trigger') || lbl.includes('trigger') || lbl.includes('start')) {
    return <IconBolt size={size} />;
  }
  if (type.includes('research') || type.includes('search') || lbl.includes('research')) {
    return <IconSearch size={size} />;
  }
  if (type.includes('router') || type.includes('classifier') || lbl.includes('classifier') || lbl.includes('router')) {
    return <IconFork size={size} />;
  }
  if (type.includes('approval') || lbl.includes('approval') || lbl.includes('human')) {
    return <IconShield size={size} />;
  }
  if (type.includes('writer') || type.includes('prompt') || lbl.includes('writer') || lbl.includes('draft')) {
    return <IconEdit size={size} />;
  }
  if (type.includes('reviewer') || lbl.includes('reviewer') || lbl.includes('qa')) {
    return <IconEye size={size} />;
  }
  if (type.includes('email') || type.includes('mail') || lbl.includes('email') || lbl.includes('crm')) {
    return <IconMail size={size} />;
  }
  if (type.includes('code') || lbl.includes('code') || lbl.includes('sandbox')) {
    return <IconCode size={size} />;
  }
  if (type.includes('synthesizer') || lbl.includes('synthesizer')) {
    return <IconCpu size={size} />;
  }
  if (type.includes('rag') || type.includes('database') || lbl.includes('rag')) {
    return <IconDatabase size={size} />;
  }
  if (type.includes('browser') || lbl.includes('browser')) {
    return <IconGlobe size={size} />;
  }
  if (type.includes('tool') || lbl.includes('tool')) {
    return <IconSettings size={size} />;
  }

  return <IconBolt size={size} />;
}

