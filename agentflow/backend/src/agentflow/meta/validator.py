"""
DAG integrity validator for Workflow Architect output.
Never trusts LLM graph output without independent deterministic structural validation.
"""
from __future__ import annotations

import re
from collections import defaultdict, deque

from agentflow.meta.schemas import WorkflowArchitectOutput


class DAGValidationError(ValueError):
    """Raised when an architect-generated workflow violates DAG rules."""
    def __init__(self, message: str, violations: list[str] | None = None) -> None:
        super().__init__(message)
        self.violations = violations or [message]


def validate_architect_graph(
    output: WorkflowArchitectOutput,
    valid_node_types: set[str],
    valid_tools: set[str],
) -> list[str]:
    """
    Validate the graph generated by Workflow Architect.
    Returns a list of violation strings. If empty, the graph is completely valid.
    """
    violations: list[str] = []

    if not output.nodes:
        return ["Workflow graph contains no nodes."]

    node_ids = {n.id for n in output.nodes}
    nodes_by_id = {n.id: n for n in output.nodes}

    # 1. Exactly one trigger node
    trigger_nodes = [n for n in output.nodes if n.type.startswith("trigger_") or n.id.startswith("trigger")]
    if len(trigger_nodes) != 1:
        violations.append(
            f"Workflow must contain exactly 1 trigger node, but found {len(trigger_nodes)}: "
            f"{[n.id for n in trigger_nodes]}"
        )
    trigger_id = trigger_nodes[0].id if trigger_nodes else None

    # 2. Node catalog validation
    for node in output.nodes:
        if node.type not in valid_node_types:
            violations.append(
                f"Node '{node.id}' uses unknown type '{node.type}'. "
                f"Available types: {sorted(valid_node_types)[:10]}..."
            )
        # Tool validation
        for tool in node.config.tools:
            if tool not in valid_tools:
                violations.append(
                    f"Node '{node.id}' requests unknown tool '{tool}'. "
                    f"Available tools: {sorted(valid_tools)}"
                )

    # 3. Edge references exist
    adj: dict[str, list[str]] = defaultdict(list)
    in_degree: dict[str, int] = {n_id: 0 for n_id in node_ids}
    has_edge: set[str] = set()

    for idx, edge in enumerate(output.edges):
        if edge.from_node not in node_ids:
            violations.append(f"Edge {idx} references nonexistent 'from' node '{edge.from_node}'.")
        if edge.to_node not in node_ids:
            violations.append(f"Edge {idx} references nonexistent 'to' node '{edge.to_node}'.")
        if edge.from_node in node_ids and edge.to_node in node_ids:
            adj[edge.from_node].append(edge.to_node)
            in_degree[edge.to_node] += 1
            has_edge.add(edge.from_node)
            has_edge.add(edge.to_node)

    # 4. No orphan nodes (single disconnected nodes)
    if len(output.nodes) > 1:
        orphans = [n_id for n_id in node_ids if n_id not in has_edge]
        if orphans:
            violations.append(f"Graph contains orphan/unconnected nodes: {orphans}")

    # 5. Cycle & feedback loop bounding check
    # We identify forward DAG edges vs backwards feedback edges
    visited: set[str] = set()
    rec_stack: set[str] = set()
    feedback_edges: list[tuple[str, str]] = []

    def dfs(curr: str) -> None:
        visited.add(curr)
        rec_stack.add(curr)
        for neighbor in adj.get(curr, []):
            if neighbor not in visited:
                dfs(neighbor)
            elif neighbor in rec_stack:
                # Cycle or feedback loop detected
                feedback_edges.append((curr, neighbor))
        rec_stack.remove(curr)

    if trigger_id and trigger_id in node_ids:
        dfs(trigger_id)

    # All feedback loops must target a node with max_loop_iterations <= 3
    for u, v in feedback_edges:
        target_node = nodes_by_id.get(v)
        if target_node:
            max_iter = getattr(target_node.config, "max_loop_iterations", 1)
            if max_iter > 3:
                violations.append(
                    f"Feedback loop from '{u}' to '{v}' has excessive max_loop_iterations ({max_iter}). "
                    f"Maximum allowed is 3."
                )

    # 6. Data Map Reference Resolution
    # Extract all {{node_id.output.field}} patterns and verify node_id is an ancestor
    # Compute reachable ancestors using BFS/DFS
    ancestors: dict[str, set[str]] = defaultdict(set)
    for root in node_ids:
        q = deque([root])
        seen = {root}
        while q:
            curr = q.popleft()
            for nxt in adj.get(curr, []):
                # ignore back edges in ancestor check
                if (curr, nxt) in feedback_edges:
                    continue
                if nxt not in seen:
                    seen.add(nxt)
                    ancestors[nxt].add(curr)
                    ancestors[nxt].update(ancestors[curr])
                    q.append(nxt)

    pattern = re.compile(r"\{\{\s*([a-zA-Z0-9_\-]+)\.(?:output|input)")
    for node in output.nodes:
        # Check in data_map
        refs = set()
        for v in node.data_map.values():
            if isinstance(v, str):
                for match in pattern.findall(v):
                    refs.add(match)

        for ref_id in refs:
            if ref_id not in node_ids:
                violations.append(
                    f"Node '{node.id}' data_map references nonexistent node '{{{{{ref_id}}}}}'."
                )
            elif ref_id != node.id and ref_id not in ancestors[node.id]:
                # It's not a topological ancestor
                violations.append(
                    f"Node '{node.id}' references '{{{{{ref_id}}}}}' which is not upstream/ancestor of '{node.id}'."
                )

    return violations
